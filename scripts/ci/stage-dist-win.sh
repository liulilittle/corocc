#!/usr/bin/env bash
# Stage the MSVC x64 distribution and pack
# corocc-<tag>-x86_64-pc-windows-msvc.zip (design v1.1 section 9.2; runs under
# Git Bash on the windows-2025 runner -- the workflow upload path uses the
# same name, asserted by ci/check-workflows.sh).
#
# Usage: scripts/ci/stage-dist-win.sh <tag>
#
# Environment:
#   BUILD_DIR  build tree (default: <root>/build; looks in Release/ too)
#   DIST_OUT   output dir (default: <root>/dist-out)
#
# Package layout (zip top level x86_64-pc-windows-msvc/):
#   lib/corocc.lib + include/corocc + lib/cmake/corocc/* + examples + README
#   corocc-config.cmake defines COROCC_BUILDING=1 for consumers (M9 probe A2:
#   without it every call site resolves to __declspec(dllimport) -> LNK2019).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TAG="${1:-}"
[ -n "$TAG" ] || { echo "usage: stage-dist-win.sh <tag>" >&2; exit 2; }

BUILD_DIR="${BUILD_DIR:-$ROOT/build}"
OUT_DIR="${DIST_OUT:-$ROOT/dist-out}"
TRIPLE="x86_64-pc-windows-msvc"

LIB=""
for cand in "$BUILD_DIR/Release/corocc.lib" "$BUILD_DIR/corocc.lib"; do
    if [ -f "$cand" ]; then LIB="$cand"; break; fi
done
[ -n "$LIB" ] || { echo "stage-dist-win: no corocc.lib under $BUILD_DIR (build Release first)" >&2; exit 1; }
[ -d "$ROOT/include/corocc" ] || { echo "stage-dist-win: missing include/corocc" >&2; exit 1; }

STAGE="$OUT_DIR/stage-$TRIPLE"
PKG="$STAGE/$TRIPLE"
rm -rf "$STAGE"
mkdir -p "$PKG/lib" "$PKG/include" "$PKG/lib/cmake/corocc" "$PKG/examples/cmake-consumer"
cp "$LIB" "$PKG/lib/corocc.lib"
cp -R "$ROOT/include/corocc" "$PKG/include/corocc"

VERSION="${TAG#v}"
MAJOR="${VERSION%%.*}"
case "$MAJOR" in ''|*[!0-9]*) MAJOR=0 ;; esac

cat > "$PKG/lib/cmake/corocc/corocc-config.cmake" <<EOF
# Generated by scripts/ci/stage-dist-win.sh -- corocc ${TAG} (${TRIPLE}).
get_filename_component(_corocc_prefix "\${CMAKE_CURRENT_LIST_DIR}/../../.." ABSOLUTE)
if(NOT TARGET corocc::corocc)
  add_library(corocc::corocc STATIC IMPORTED)
  set_target_properties(corocc::corocc PROPERTIES
    IMPORTED_LOCATION "\${_corocc_prefix}/lib/corocc.lib"
    INTERFACE_INCLUDE_DIRECTORIES "\${_corocc_prefix}/include"
    INTERFACE_COMPILE_DEFINITIONS "COROCC_BUILDING=1")
endif()
set(corocc_FOUND TRUE)
EOF

cat > "$PKG/lib/cmake/corocc/corocc-config-version.cmake" <<EOF
set(PACKAGE_VERSION "${VERSION}")
if(PACKAGE_FIND_VERSION_MAJOR EQUAL ${MAJOR})
    set(PACKAGE_VERSION_COMPATIBLE TRUE)
    if(PACKAGE_FIND_VERSION VERSION_EQUAL PACKAGE_VERSION)
        set(PACKAGE_VERSION_EXACT TRUE)
    endif()
endif()
EOF

GIT_REV="$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)"
DATE_UTC="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
cat > "$PKG/README.txt" <<EOF
corocc $TAG -- prebuilt static library (MSVC x64)
triple : $TRIPLE
commit : $GIT_REV
built  : $DATE_UTC (UTC)
flags  : released by .github/workflows/release.yml (COROCC_LTCG on)
usage  : see examples/cmake-consumer/
         cmake -S examples/cmake-consumer -B build \\
               -DCMAKE_PREFIX_PATH=<this directory> -G "Visual Studio 17 2022" -A x64
         cmake --build build --config Release
EOF

cat > "$PKG/examples/cmake-consumer/CMakeLists.txt" <<'EOF'
cmake_minimum_required(VERSION 3.16)
project(corocc_consumer C)
find_package(corocc REQUIRED CONFIG)
add_executable(consumer main.c)
target_link_libraries(consumer PRIVATE corocc::corocc)
EOF

cat > "$PKG/examples/cmake-consumer/main.c" <<'EOF'
/* Minimal consumer of the prebuilt package: create a coroutine object,
 * check its state, destroy it. */
#include <corocc/coro.h>
#include <stdio.h>

static void entry(void* arg) { (void)arg; }

int main(void) {
    coro_t* c = NULL;
    if (coro_create(&c, NULL, entry, NULL) != CORO_OK) {
        fprintf(stderr, "coro_create failed\n");
        return 1;
    }
    if (coro_get_state(c) != CORO_NEW) {
        fprintf(stderr, "unexpected state\n");
        coro_destroy(c);
        return 1;
    }
    if (coro_destroy(c) != CORO_OK) {
        fprintf(stderr, "coro_destroy failed\n");
        return 1;
    }
    printf("corocc consumer: OK\n");
    return 0;
}
EOF

mkdir -p "$OUT_DIR"
ZIP="$OUT_DIR/corocc-$TAG-$TRIPLE.zip"
if command -v cygpath >/dev/null 2>&1; then
    WIN_PKG="$(cygpath -w "$PKG")"
    WIN_ZIP="$(cygpath -w "$ZIP")"
else
    WIN_PKG="$PKG"
    WIN_ZIP="$ZIP"
fi
powershell.exe -NoProfile -NonInteractive -Command \
    "Compress-Archive -LiteralPath '${WIN_PKG//\'/\'\'}' -DestinationPath '${WIN_ZIP//\'/\'\'}' -Force"
[ -f "$ZIP" ] || { echo "stage-dist-win: zip not created" >&2; exit 1; }
echo "stage-dist-win: $ZIP"
