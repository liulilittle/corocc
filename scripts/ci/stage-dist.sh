#!/usr/bin/env bash
# Stage one prebuilt distribution tree and pack corocc-<tag>-<triple>.tar.gz
# (the workflow upload path uses the same name -- ci/check-workflows.sh
# asserts the naming chain).
#
# Usage: scripts/ci/stage-dist.sh <site> <triple> <tag>
#   <site>  build-test.sh site name; the build tree is build-ci-<site>
#
# Environment:
#   BUILD_DIR  build tree (default: <root>/build-ci-<site>)
#   DIST_OUT   output dir (default: <root>/dist-out)
#
# Package layout (tar top level <triple>/):
#   lib/libcorocc.a
#   include/corocc/*.h|.hpp           (public headers)
#   lib/cmake/corocc/corocc-config.cmake
#   lib/cmake/corocc/corocc-config-version.cmake
#   examples/cmake-consumer/{CMakeLists.txt,main.c}
#   README.txt                        (tag, triple, commit, cc, flags, date)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SITE="${1:-}"; TRIPLE="${2:-}"; TAG="${3:-}"
if [ -z "$SITE" ] || [ -z "$TRIPLE" ] || [ -z "$TAG" ]; then
    echo "usage: stage-dist.sh <site> <triple> <tag>" >&2
    exit 2
fi

BUILD_DIR="${BUILD_DIR:-$ROOT/build-ci-$SITE}"
OUT_DIR="${DIST_OUT:-$ROOT/dist-out}"
CACHE="$BUILD_DIR/CMakeCache.txt"
LIB="$BUILD_DIR/libcorocc.a"

[ -f "$LIB" ] || { echo "stage-dist: missing $LIB (build the site first)" >&2; exit 1; }
[ -d "$ROOT/include/corocc" ] || { echo "stage-dist: missing include/corocc" >&2; exit 1; }

STAGE="$OUT_DIR/stage-$TRIPLE"
PKG="$STAGE/$TRIPLE"
rm -rf "$STAGE"
mkdir -p "$PKG/lib" "$PKG/include" "$PKG/lib/cmake/corocc" "$PKG/examples/cmake-consumer"
cp "$LIB" "$PKG/lib/libcorocc.a"
cp -R "$ROOT/include/corocc" "$PKG/include/corocc"

# 32-bit ABI link interface: mirror cmake/arch_select.cmake:102-116 -- inject
# -latomic (as INTERFACE_LINK_LIBRARIES atomic) only when the build-width probe
# found no inline 64-bit CAS on a 32-bit build. Pointer width comes from the
# cache when present, otherwise from the compiler ABI file (CMake 3.28 keeps it
# in CMakeCCompiler.cmake, not in CMakeCache.txt).
ATOMIC_LINE=""
VOIDP=""
if [ -f "$CACHE" ]; then
    VOIDP="$(grep -E '^CMAKE_SIZEOF_VOID_P:' "$CACHE" | head -1 | cut -d= -f2 || true)"
fi
if [ -z "$VOIDP" ]; then
    VOIDP="$(grep -hE '^set\(CMAKE_C_SIZEOF_DATA_PTR ' "$BUILD_DIR"/CMakeFiles/*/CMakeCCompiler.cmake 2>/dev/null \
            | head -1 | grep -oE '[0-9]+' || true)"
fi
if [ -z "$VOIDP" ]; then
    echo "stage-dist: cannot determine pointer width (cache + CMakeCCompiler.cmake)" >&2
    exit 1
fi
if [ "$VOIDP" = "4" ] && ! grep -q '^COROCC_HAVE_INLINE_U64_ATOMICS:INTERNAL=1$' "$CACHE"; then
    ATOMIC_LINE="set_property(TARGET corocc::corocc APPEND PROPERTY INTERFACE_LINK_LIBRARIES atomic)"
fi

VERSION="${TAG#v}"
MAJOR="${VERSION%%.*}"
case "$MAJOR" in ''|*[!0-9]*) MAJOR=0 ;; esac

cat > "$PKG/lib/cmake/corocc/corocc-config.cmake" <<EOF
# Generated by scripts/ci/stage-dist.sh -- corocc ${TAG} (${TRIPLE}).
get_filename_component(_corocc_prefix "\${CMAKE_CURRENT_LIST_DIR}/../../.." ABSOLUTE)
include(CMakeFindDependencyMacro)
find_dependency(Threads)
if(NOT TARGET corocc::corocc)
  add_library(corocc::corocc STATIC IMPORTED)
  set_target_properties(corocc::corocc PROPERTIES
    IMPORTED_LOCATION "\${_corocc_prefix}/lib/libcorocc.a"
    INTERFACE_INCLUDE_DIRECTORIES "\${_corocc_prefix}/include"
    INTERFACE_LINK_LIBRARIES "Threads::Threads")
${ATOMIC_LINE:+  $ATOMIC_LINE}
endif()
set(corocc_FOUND TRUE)
EOF

cat > "$PKG/lib/cmake/corocc/corocc-config-version.cmake" <<EOF
set(PACKAGE_VERSION "${VERSION}")
if(PACKAGE_FIND_VERSION_MAJOR EQUAL ${MAJOR})
    set(PACKAGE_VERSION_COMPATIBLE TRUE)
    if(PACKAGE_FIND_VERSION VERSION_EQUAL PACKAGE_VERSION)
        set(PACKAGE_VERSION_EXACT TRUE)
    endif()
endif()
EOF

GIT_REV="$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)"
DATE_UTC="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
CC_INFO=""
if [ -f "$CACHE" ]; then
    CC_INFO="$(grep -E '^CMAKE_C_COMPILER:(FILEPATH|STRING)=' "$CACHE" | head -1 | cut -d= -f2 || true)"
fi
cat > "$PKG/README.txt" <<EOF
corocc $TAG -- prebuilt static library
triple : $TRIPLE
commit : $GIT_REV
built  : $DATE_UTC (UTC)
cc     : ${CC_INFO:-unknown}
flags  : -static (see .github/workflows/release.yml)
usage  : see examples/cmake-consumer/
         cmake -S examples/cmake-consumer -B build \\
               -DCMAKE_PREFIX_PATH=<this directory>
         cmake --build build
EOF

cat > "$PKG/examples/cmake-consumer/CMakeLists.txt" <<'EOF'
cmake_minimum_required(VERSION 3.16)
project(corocc_consumer C)
find_package(corocc REQUIRED CONFIG)
add_executable(consumer main.c)
target_link_libraries(consumer PRIVATE corocc::corocc)
EOF

cat > "$PKG/examples/cmake-consumer/main.c" <<'EOF'
/* Minimal consumer of the prebuilt package: create a coroutine object,
 * check its state, destroy it. */
#include <corocc/coro.h>
#include <stdio.h>

static void entry(void* arg) { (void)arg; }

int main(void) {
    coro_t* c = NULL;
    if (coro_create(&c, NULL, entry, NULL) != CORO_OK) {
        fprintf(stderr, "coro_create failed\n");
        return 1;
    }
    if (coro_get_state(c) != CORO_NEW) {
        fprintf(stderr, "unexpected state\n");
        coro_destroy(c);
        return 1;
    }
    if (coro_destroy(c) != CORO_OK) {
        fprintf(stderr, "coro_destroy failed\n");
        return 1;
    }
    printf("corocc consumer: OK\n");
    return 0;
}
EOF

mkdir -p "$OUT_DIR"
TARBALL="$OUT_DIR/corocc-$TAG-$TRIPLE.tar.gz"
tar --sort=name --mtime='UTC 2020-01-01' --owner=0 --group=0 --numeric-owner \
    -czf "$TARBALL" -C "$STAGE" "$TRIPLE"
echo "stage-dist: $TARBALL"
tar -tzf "$TARBALL" | sed -n '1,5p'
